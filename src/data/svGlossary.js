function dedupe(entries) {
  const seen = new Set();
  return entries.filter(e => {
    const key = e.sv_natural.trim().toLowerCase();
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

// Returns a compact, prompt-ready grounding block listing verified real-world
// Swedish terminology, grouped by source. Not matched against `text` — the
// glossary is small and curated enough to include in full for Help Center
// article proofreading, so the model always has the reference regardless of
// which terms happen to appear in a given article.
export function getGlossaryContext(text, { maxEntries = 60 } = {}) {
  if (!SV_GLOSSARY.length) return '';

  const entries = dedupe(SV_GLOSSARY).slice(0, maxEntries);
  const bySource = new Map();
  for (const e of entries) {
    if (!bySource.has(e.source_name)) bySource.set(e.source_name, []);
    bySource.get(e.source_name).push(e);
  }

  const sections = [...bySource.entries()].map(([source, items]) => {
    const lines = items.map(e => `  - ${e.en} → "${e.sv_natural}"${e.context ? ` (${e.context})` : ''}`);
    return `${source}:\n${lines.join('\n')}`;
  });

  return `\nTERMINOLOGY GROUNDING — verified real-world Swedish usage from other crypto-exchange and financial help centers. Use these as reference for natural, market-correct wording. Adapt naturally to context — don't force an awkward insertion just to match:\n${sections.join('\n')}\n`;
}
